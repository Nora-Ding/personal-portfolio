const languageToggle = document.getElementById('language-toggle');
const contactForm = document.getElementById('contact-form');
let currentLanguage = localStorage.getItem('portfolio-language') || 'zh';

function setLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];

  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = dictionary.pageTitle;

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.innerHTML = dictionary[key];
    }
  });

  languageToggle.textContent = dictionary.toggle;
  languageToggle.setAttribute(
    'aria-label',
    language === 'zh' ? 'Switch to English' : '切换到中文'
  );
  localStorage.setItem('portfolio-language', language);
}

languageToggle.addEventListener('click', () => {
  setLanguage(currentLanguage === 'zh' ? 'en' : 'zh');
});

contactForm.addEventListener('submit', function (e) {
  e.preventDefault();
  const btn = this.querySelector('button[type="submit"]');
  btn.textContent = translations[currentLanguage].sent;
  btn.disabled = true;
  setTimeout(() => {
    btn.textContent = translations[currentLanguage]['contact.submit'];
    btn.disabled = false;
    this.reset();
  }, 2000);
});

document.querySelectorAll('a[href^="#"]').forEach(anchor => {
  anchor.addEventListener('click', function (e) {
    e.preventDefault();
    const target = document.querySelector(this.getAttribute('href'));
    if (target) {
      target.scrollIntoView({ behavior: 'smooth' });
    }
  });
});

setLanguage(currentLanguage);
