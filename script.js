function projectChinaCoordinate(coordinate) {
  const [lng, lat] = coordinate;
  const minLng = 73;
  const maxLng = 135;
  const minLat = 17;
  const maxLat = 54;
  const width = 1000;
  const height = 620;
  const x = ((lng - minLng) / (maxLng - minLng)) * width;
  const y = ((maxLat - lat) / (maxLat - minLat)) * height;

  return [x, y];
}

function polygonToPath(polygon) {
  return polygon.map(ring => ring.map((coordinate, index) => {
    const [x, y] = projectChinaCoordinate(coordinate);
    return `${index === 0 ? 'M' : 'L'}${x.toFixed(2)} ${y.toFixed(2)}`;
  }).join(' ') + ' Z').join(' ');
}

function featureToPath(feature) {
  const { geometry } = feature;
  if (!geometry) {
    return '';
  }

  if (geometry.type === 'Polygon') {
    return polygonToPath(geometry.coordinates);
  }

  if (geometry.type === 'MultiPolygon') {
    return geometry.coordinates.map(polygonToPath).join(' ');
  }

  return '';
}

