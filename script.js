function renderGeoJsonSvgMap(geojson) {
  const visitedProvinces = getVisitedProvinceNames();
  svgProvinceElements.clear();
  svgCityElements.clear();
  leafletTravelMap.innerHTML = '';

  const svg = createSvgElement('svg');
  svg.setAttribute('class', 'geojson-travel-svg');
  svg.setAttribute('viewBox', getTravelMapViewBox());
  svg.setAttribute('role', 'img');
  svg.setAttribute('aria-label', '中国旅行策划互动地图');

  const provinceGroup = createSvgElement('g');
  const cityGroup = createSvgElement('g');
  svg.appendChild(provinceGroup);
  svg.appendChild(cityGroup);

  geojson.features.forEach(feature => {
    const provinceName = feature.properties.name;
    const path = createSvgElement('path');
    path.setAttribute('d', featureToPath(feature));
    path.setAttribute('class', `geojson-province${visitedProvinces.has(provinceName) ? ' is-visited' : ''}`);
    path.dataset.province = provinceName;
    path.setAttribute('role', 'button');
    path.setAttribute('tabindex', '0');
    path.setAttribute('aria-label', provinceName);
    path.addEventListener('click', () => {
      const [firstCity] = getProvinceCities(provinceName);
      if (firstCity) {
        selectTravelCity(firstCity.id);
      }
    });
    path.addEventListener('keydown', event => {
      if (event.key !== 'Enter' && event.key !== ' ') {
        return;
      }

      event.preventDefault();
      const [firstCity] = getProvinceCities(provinceName);
      if (firstCity) {
        selectTravelCity(firstCity.id);
      }
    });
    provinceGroup.appendChild(path);
    svgProvinceElements.set(provinceName, path);
  });

  travelCities.forEach(city => {
    const [primary] = toneColors[city.tone] || toneColors.river;
    const [x, y] = projectChinaCoordinate([city.lng, city.lat]);
    const group = createSvgElement('g');
    const hitArea = createSvgElement('circle');
    const circle = createSvgElement('circle');
    const label = createSvgElement('text');

    group.setAttribute('class', 'geojson-city-group travel-city-marker');
    group.dataset.cityId = city.id;
    group.setAttribute('role', 'button');
    group.setAttribute('tabindex', '0');
    group.setAttribute('aria-label', `${city.zh} / ${city.en}`);
    group.style.setProperty('--city-color', primary);
    group.addEventListener('click', event => {
      event.stopPropagation();
      selectTravelCity(city.id);
    });
    group.addEventListener('keydown', event => {
      if (event.key !== 'Enter' && event.key !== ' ') {
        return;
      }

      event.preventDefault();
      selectTravelCity(city.id);
    });

    hitArea.setAttribute('class', 'geojson-city-hit-area');
    hitArea.setAttribute('cx', x.toFixed(2));
    hitArea.setAttribute('cy', y.toFixed(2));
    hitArea.setAttribute('r', '13');
    circle.setAttribute('class', 'geojson-city-dot');
    circle.setAttribute('cx', x.toFixed(2));
    circle.setAttribute('cy', y.toFixed(2));
    circle.setAttribute('r', '5');
    const labelPosition = getCityLabelPosition(city, x, y);
    label.setAttribute('class', 'geojson-city-label');
    label.setAttribute('x', labelPosition.x.toFixed(2));
    label.setAttribute('y', labelPosition.y.toFixed(2));
    label.setAttribute('text-anchor', labelPosition.anchor);
    label.textContent = city.zh;

    group.appendChild(hitArea);
    group.appendChild(circle);
    group.appendChild(label);
    cityGroup.appendChild(group);
    svgCityElements.set(city.id, group);
  });

  leafletTravelMap.appendChild(svg);
  renderTravelMapState();
}

function hydrateInlineSvgMap() {
  if (!leafletTravelMap) {
    return false;
  }

  const svg = leafletTravelMap.querySelector('.geojson-travel-svg');
  if (!svg) {
    return false;
  }

  if (inlineSvgMapHydrated) {
    syncTravelMapViewBox();
    renderTravelMapState();
    return true;
  }

  syncTravelMapViewBox();

  svgProvinceElements.clear();
  svgCityElements.clear();

  svg.querySelectorAll('.geojson-province[data-province]').forEach(element => {
    const provinceName = element.dataset.province;
    svgProvinceElements.set(provinceName, element);
    element.addEventListener('click', () => {
      const [firstCity] = getProvinceCities(provinceName);
      if (firstCity) {
        selectTravelCity(firstCity.id);
      }
    });
    element.addEventListener('keydown', event => {
      if (event.key !== 'Enter' && event.key !== ' ') {
        return;
      }

      event.preventDefault();
      const [firstCity] = getProvinceCities(provinceName);
      if (firstCity) {
        selectTravelCity(firstCity.id);
      }
    });
  });

  svg.querySelectorAll('.geojson-city-group[data-city-id]').forEach(element => {
    const city = travelCities.find(item => item.id === element.dataset.cityId);
    if (!city) {
      return;
    }

    svgCityElements.set(city.id, element);
    const dot = element.querySelector('.geojson-city-dot');
    if (dot && !element.querySelector('.geojson-city-hit-area')) {
      const hitArea = createSvgElement('circle');
      hitArea.setAttribute('class', 'geojson-city-hit-area');
      hitArea.setAttribute('cx', dot.getAttribute('cx'));
      hitArea.setAttribute('cy', dot.getAttribute('cy'));
      hitArea.setAttribute('r', '13');
      element.insertBefore(hitArea, dot);
    }
    if (dot) {
      const label = element.querySelector('.geojson-city-label');
      const x = Number(dot.getAttribute('cx'));
      const y = Number(dot.getAttribute('cy'));
      const labelPosition = getCityLabelPosition(city, x, y);
      if (label) {
        label.setAttribute('x', labelPosition.x.toFixed(2));
        label.setAttribute('y', labelPosition.y.toFixed(2));
        label.setAttribute('text-anchor', labelPosition.anchor);
      }
    }
    element.addEventListener('click', event => {
      event.stopPropagation();
      selectTravelCity(city.id);
    });
    element.addEventListener('keydown', event => {
      if (event.key !== 'Enter' && event.key !== ' ') {
        return;
      }

      event.preventDefault();
      selectTravelCity(city.id);
    });
  });

  inlineSvgMapHydrated = true;
  renderTravelMapState();
  return true;
}

function initTravelMap() {
  if (!leafletTravelMap || typeof L === 'undefined') {
    showMapFallback();
    return;
  }

  travelMap = L.map('leaflet-travel-map', {
    zoomControl: true,
    attributionControl: false,
    dragging: true,
    scrollWheelZoom: false,
    doubleClickZoom: false,
    minZoom: 3,
    maxZoom: 7
  });

  travelMap.setView([35.8617, 104.1954], 4);
  renderCityMarkers();

  loadChinaGeojson()
    .then(renderProvinceLayer)
    .catch(showMapFallback);
}

function bootTravelMap(retries = 40) {
  if (hydrateInlineSvgMap()) {
    return;
  }

  if (typeof L !== 'undefined') {
    initTravelMap();
    return;
  }

  if (!leafletFallbackRequested) {
    leafletFallbackRequested = true;
    initGeoJsonSvgMap();
    return;
  }

  if (retries <= 0) {
    return;
  }

  window.setTimeout(() => bootTravelMap(retries - 1), 250);
}

