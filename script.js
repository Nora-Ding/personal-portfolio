function getCityLabelPosition(city, x, y) {
  const offset = cityLabelOffsets[city.id] || { dx: 0, dy: -10 };

  return {
    x: x + offset.dx,
    y: y + offset.dy,
    anchor: offset.dx < 0 ? 'end' : offset.dx > 0 ? 'start' : 'middle'
  };
}

function loadChinaGeojson() {
  if (typeof chinaProvinceGeojson !== 'undefined') {
    return Promise.resolve(chinaProvinceGeojson);
  }

  if (typeof globalThis !== 'undefined' && globalThis.chinaProvinceGeojson) {
    return Promise.resolve(globalThis.chinaProvinceGeojson);
  }

  if (typeof window !== 'undefined' && window.chinaProvinceGeojson) {
    return Promise.resolve(window.chinaProvinceGeojson);
  }

  if (typeof fetch !== 'function') {
    return Promise.reject(new Error('Map data loader is unavailable'));
  }

  return fetch('assets/china-provinces.geojson')
    .then(response => {
      if (!response.ok) {
        throw new Error('Map data request failed');
      }
      return response.json();
    });
}

