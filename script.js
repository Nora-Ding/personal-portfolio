function getProvinceStyle(provinceName, options = {}) {
  const visitedProvinces = getVisitedProvinceNames();
  const selectedCity = getSelectedCity();
  const isVisited = visitedProvinces.has(provinceName);
  const isSelected = selectedCity.province === provinceName;

  return {
    color: options.hover ? '#111827' : isSelected ? '#ea580c' : '#ffffff',
    fillColor: isSelected ? '#f97316' : isVisited ? '#4f46e5' : '#e5e7eb',
    fillOpacity: isSelected ? 0.72 : isVisited ? 0.5 : 0.34,
    opacity: 1,
    weight: options.hover || isSelected ? 2.4 : 1.1
  };
}

function renderTravelMapState() {
  const selectedCity = getSelectedCity();
  const selectedProvinceName = selectedCity.province;

  if (travelMap) {
    provinceLayers.forEach((layer, provinceName) => {
      layer.setStyle(getProvinceStyle(provinceName));
      if (provinceName === selectedProvinceName) {
        selectedProvinceLayer = layer;
        layer.bringToFront();
      }
    });

    cityMarkers.forEach((marker, cityId) => {
      const city = travelCities.find(item => item.id === cityId);
      const [primary] = toneColors[city.tone] || toneColors.river;
      const isSelected = cityId === selectedCityId;

      marker.setStyle({
        color: '#ffffff',
        fillColor: isSelected ? '#ef4444' : primary,
        fillOpacity: 0.95,
        opacity: 1,
        radius: isSelected ? 8 : 5,
        weight: isSelected ? 3 : 2
      });

      if (isSelected) {
        marker.bringToFront();
        marker.openTooltip();
      }
    });
  }

  svgProvinceElements.forEach((element, provinceName) => {
    element.classList.toggle('is-selected', provinceName === selectedProvinceName);
  });

  svgCityElements.forEach((element, cityId) => {
    const isSelected = cityId === selectedCityId;
    const dot = element.querySelector('.geojson-city-dot');

    element.classList.toggle('is-selected', isSelected);
    if (dot) {
      dot.setAttribute('r', isSelected ? '8' : '5');
    }
    if (isSelected && element.parentNode) {
      element.parentNode.appendChild(element);
    }
  });
}

function renderProvinceLayer(geojson) {
  const visitedProvinces = getVisitedProvinceNames();

  provinceLayer = L.geoJSON(geojson, {
    style: feature => getProvinceStyle(feature.properties.name),
    onEachFeature: (feature, layer) => {
      const provinceName = feature.properties.name;
      provinceLayers.set(provinceName, layer);

      layer.bindTooltip(provinceName, {
        className: 'travel-province-tooltip',
        direction: 'center',
        sticky: true
      });
      layer.on('add', () => {
        const provinceElement = layer.getElement();
        if (provinceElement) {
          provinceElement.dataset.province = provinceName;
          provinceElement.setAttribute('role', 'button');
          provinceElement.setAttribute('tabindex', '0');
          provinceElement.setAttribute('aria-label', provinceName);
          provinceElement.addEventListener('click', () => {
            if (!visitedProvinces.has(provinceName)) {
              return;
            }

            const [firstCity] = getProvinceCities(provinceName);
            if (firstCity) {
              selectTravelCity(firstCity.id);
            }
          });
          provinceElement.addEventListener('keydown', event => {
            if (event.key !== 'Enter' && event.key !== ' ') {
              return;
            }

            event.preventDefault();
            if (!visitedProvinces.has(provinceName)) {
              return;
            }

            const [firstCity] = getProvinceCities(provinceName);
            if (firstCity) {
              selectTravelCity(firstCity.id);
            }
          });
        }
      });

      layer.on({
        mouseover: () => layer.setStyle(getProvinceStyle(provinceName, { hover: true })),
        mouseout: () => layer.setStyle(getProvinceStyle(provinceName)),
        click: () => {
          if (!visitedProvinces.has(provinceName)) {
            return;
          }

          const [firstCity] = getProvinceCities(provinceName);
          if (firstCity) {
            selectTravelCity(firstCity.id);
          }
        }
      });
    }
  }).addTo(travelMap);

  if (cityMarkerLayer) {
    cityMarkerLayer.bringToFront();
  }

  travelMap.fitBounds(provinceLayer.getBounds(), {
    padding: [12, 12],
    animate: false
  });
  renderTravelMapState();
}

